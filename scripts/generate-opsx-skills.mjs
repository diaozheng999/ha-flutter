#!/usr/bin/env node
/**
 * Bridge OpenSpec slash commands to universal agent skills.
 *
 * Why this exists: `openspec init` natively supports ~30 tools, but the
 * `skills` CLI ecosystem covers ~70 agents, most of which read the universal
 * `.agents/skills/` directory (amp, warp, zed, zcode, replit, ...). For those
 * agents OpenSpec generates nothing. This script fills the gap by MOVING the
 * Claude Code commands that `openspec init --tools claude` just generated:
 *
 *   .claude/commands/opsx/<id>.md  ->  .agents/skills/opsx-<id>/SKILL.md
 *
 * and rewriting every `/opsx:<id>` reference to `/opsx-<id>` (skills cannot
 * contain a colon in their name). Agents that read `.agents/skills/` --
 * including Claude Code itself -- invoke the workflow as `/opsx-<id>`.
 * Agents with their own native OpenSpec output (e.g. `.cursor/commands/`,
 * `.pi/prompts/` when selected in `openspec init --tools`) are left untouched.
 *
 * Idempotent: re-runs are no-ops when the commands have already been moved.
 * Run via scripts/setup.ps1 / scripts/setup.sh, after `openspec init`.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, '.claude', 'commands', 'opsx');
const outDir = path.join(root, '.agents', 'skills');

/** Extract a frontmatter scalar (single-line) value, stripping quotes. */
function frontmatterValue(frontmatter, key) {
  const m = frontmatter.match(new RegExp(`^${key}:\\s*(.+)$`, 'm'));
  if (!m) return undefined;
  return m[1].trim().replace(/^["']|["']$/g, '');
}

function convert(commandFile) {
  const id = path.basename(commandFile, '.md');
  const skillName = `opsx-${id}`;
  const raw = fs.readFileSync(commandFile, 'utf8');

  const parts = raw.split(/^---\s*$/m);
  // parts[0] = '' (before first ---), parts[1] = frontmatter, parts[2..] = body
  if (parts.length < 3) {
    throw new Error(`${commandFile}: expected YAML frontmatter delimited by ---`);
  }
  let description =
    frontmatterValue(parts[1], 'description') ?? `OpenSpec workflow: ${id}`;
  if (!/[.!?]$/.test(description)) description += '.';
  const body = parts.slice(2).join('---').replace(/opsx:/g, 'opsx-').trim();

  const skill = `---
name: ${skillName}
description: "${description.replace(/"/g, '\\"')} Invoke with /${skillName}."
license: MIT
compatibility: Requires openspec CLI.
metadata:
  author: openspec
  source: generated by scripts/generate-opsx-skills.mjs from .claude/commands/opsx/${id}.md
---

${body}
`;

  const skillDir = path.join(outDir, skillName);
  fs.mkdirSync(skillDir, { recursive: true });
  fs.writeFileSync(path.join(skillDir, 'SKILL.md'), skill);
  fs.rmSync(commandFile);
  return skillName;
}

// --- 1. Move + rename commands -> skills -------------------------------------
const existingBridged = fs.existsSync(outDir)
  ? fs.readdirSync(outDir).filter((d) => d.startsWith('opsx-'))
  : [];

if (!fs.existsSync(srcDir)) {
  if (existingBridged.length > 0) {
    console.log(
      `generate-opsx-skills: nothing to do (${existingBridged.length} opsx-* skills already in .agents/skills/).`
    );
  } else {
    console.error(
      'generate-opsx-skills: .claude/commands/opsx/ not found and no opsx-* skills exist.\n' +
        'Run `npx openspec init --tools claude` first (the setup script does this).'
    );
    process.exitCode = 1;
  }
} else {
  const files = fs.readdirSync(srcDir).filter((f) => f.endsWith('.md'));
  const moved = files.map((f) => convert(path.join(srcDir, f)));
  // Remove the now-empty opsx command dir so Claude Code doesn't list stale /opsx:* commands.
  if (fs.readdirSync(srcDir).length === 0) fs.rmSync(srcDir, { recursive: true });
  console.log(
    `generate-opsx-skills: moved ${moved.length} commands to .agents/skills/ (${moved.join(', ')}).`
  );
}

// --- 2. Prune legacy openspec-* skills from the universal dir -----------------
// OpenSpec <=1.2 wrote openspec-* skills into .agents/skills/; current versions
// write them per-tool (e.g. .claude/skills/). Leftovers duplicate the opsx-*
// workflow for every universal-dir agent, so drop them.
if (fs.existsSync(outDir)) {
  const legacy = fs
    .readdirSync(outDir)
    .filter((d) => d.startsWith('openspec-'));
  for (const dir of legacy) {
    fs.rmSync(path.join(outDir, dir), { recursive: true, force: true });
  }
  if (legacy.length > 0) {
    console.log(
      `generate-opsx-skills: pruned ${legacy.length} legacy openspec-* skill dirs from .agents/skills/.`
    );
  }
}
